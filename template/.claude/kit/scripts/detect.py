def kit_file(rel):
    """The kit's version of a path, when the kit ships one."""
    if not rel.startswith(".claude/"):
        return None
    path = os.path.join(KIT_TEMPLATE, rel[len(".claude/"):])
    return path if os.path.isfile(path) else None


def status_of(rel, default):
    path = os.path.join(ROOT, rel)
    try:
        head = open(path, errors="replace").read(4096) if os.path.isfile(path) else ""
    except OSError:
        head = ""
    if rel == "AGENTS.md":
        # Only the kit's managed block in it means the file is the kit's; anything else is yours.
        text = re.sub(r"<!-- agent-flow-kit:begin -->.*?<!-- agent-flow-kit:end -->", "", open(path).read(), flags=re.S)
        return "kit" if not text.strip() else default
    if any(m in head for m in MARKERS):
        return "kit"
    if rel == ".claude/settings.json":
        # Only the hooks the installer added means the file is the kit's.
        try:
            cfg = json.load(open(path))
            cmds = [h.get("command", "") for gs in cfg.get("hooks", {}).values() for g in gs for h in g.get("hooks", [])]
            if set(cfg) <= {"hooks"} and cmds and all("kit/hooks/flow.py" in c for c in cmds):
                return "kit"
        except (OSError, ValueError, AttributeError):
            pass
    if rel.startswith(".claude/kit/"):
        return "kit"
    ours = kit_file(rel)
    if ours:
        return "kit" if filecmp.cmp(ours, path, shallow=False) else "conflict"
    return default


def scan():
    seen, items = set(), []
    for pattern, tool, what, default in KNOWN:
        for path in sorted(glob.glob(os.path.join(ROOT, pattern))):
            rel = os.path.relpath(path, ROOT)
            if rel in seen or not os.path.exists(path):
                continue
            seen.add(rel)
            items.append({"path": rel, "tool": tool, "what": what, "status": status_of(rel, default)})
    return items


def main(args):
    items = scan()
    if "--json" in args:
        print(json.dumps(items, indent=2))
        return 0
    mine = [i for i in items if i["status"] != "kit"]
    if not mine:
        print("No other AI agent configuration found.")
        return 0
    print("AI agent configuration already in this repository:")
    for i in mine:
        print(f"  {i['status']:8}  {i['path']:42} {i['tool']}, {i['what']}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
