#!/usr/bin/env python3
"""Lists the AI agent configuration already in a repository, and how each item relates to the kit.

Usage: detect.py [--json]

Status of each item:
  kit       written by the kit (generated header, or identical to the kit's file)
  conflict  same path as a kit file, different content (the installer kept yours)
  overlap   instructions or a workflow that may repeat or contradict the flow
  other     configuration the flow does not touch (MCP servers, settings)
/flow-setup existing walks through each item with the dev.
"""
import filecmp
import glob
import json
import os
import re
import sys

