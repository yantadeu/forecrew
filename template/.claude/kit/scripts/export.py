#!/usr/bin/env python3
"""Projects the Claude Code sources of Forecrew for Cursor and Codex.

Usage: export.py [--tools cursor,codex,copilot] [--check]
       (no --tools: the tools that already have projections here, else cursor,codex)

The sources stay in .claude/ (agents, the task skill, the protocol, /product-source);
everything written here is output. Re-run after editing a source. Output is byte-stable (no
timestamp), so --check fails when a projection is stale, which a CI job can assert.

  cursor  .cursor/rules/task.mdc, .cursor/rules/agent-<role>.mdc,
          .cursor/commands/<command>.md for each .claude/commands/*.md
  codex   a managed block in AGENTS.md (the rest of the file is kept)
  copilot .github/agents/<role>.agent.md, .github/prompts/<command>.prompt.md and
          .github/prompts/task.prompt.md (Copilot also reads the AGENTS.md block)
"""
import argparse
import glob
import json
import os
import re
import sys

ROOT = os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd()
HEADER = "<!-- GENERATED by .claude/kit/scripts/export.py from .claude/. Do not edit: edit the source and re-run. -->"
BEGIN, END = "<!-- agent-flow-kit:begin -->", "<!-- agent-flow-kit:end -->"


def split(path):
    """(frontmatter dict, body) of a Markdown file with optional YAML-ish frontmatter."""
    text = open(path).read()
    meta = {}
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if m:
        for line in m.group(1).splitlines():
            k, _, v = line.partition(":")
            if v:
                meta[k.strip()] = v.strip().strip('"')
        text = text[m.end():]
    return meta, text.strip() + "\n"


def mdc(description, body):
    desc = description.replace('"', "'")
    return f'---\ndescription: "{desc}"\nalwaysApply: false\n---\n{HEADER}\n\n{body}'


def roles():
    """Role files in flow order (flow.json stages), then any other agent alphabetically."""
    try:
        order = list(json.load(open(os.path.join(ROOT, ".claude", "flow.json")))["stages"])
    except (OSError, ValueError, KeyError):
        order = []
    paths = glob.glob(os.path.join(ROOT, ".claude", "agents", "*.md"))
    rank = lambda p: (order.index(os.path.basename(p)[:-3]) if os.path.basename(p)[:-3] in order else len(order), p)
    return sorted(paths, key=rank)


def cursor():
    out = {}
    meta, body = split(os.path.join(ROOT, ".claude", "skills", "task", "SKILL.md"))
    _, protocol = split(os.path.join(ROOT, ".claude", "kit", "PROTOCOL.md"))
    names = [os.path.basename(p)[:-3] for p in roles()]
    body = body.replace("$ARGUMENTS", "the task the dev gave")
    guide = ("\n## In Cursor\n\nCursor has no subagents here: run each stage in a new chat, "
             "attaching the role rule (" + ", ".join(f"`@agent-{n}`" for n in names) +
             ") and the work directory path. The stage gate hook is Claude Code only: "
             "`bash .claude/kit/scripts/work.sh status` is the gate.\n")
    out[".cursor/rules/task.mdc"] = mdc(meta.get("description", "Agent flow"), body + guide + "\n" + protocol)
    for p in roles():
        m, b = split(p)
        out[f".cursor/rules/agent-{os.path.basename(p)[:-3]}.mdc"] = mdc(m.get("description", ""), b)
    for cmd in sorted(glob.glob(os.path.join(ROOT, ".claude", "commands", "*.md"))):
        _, b = split(cmd)
        out[".cursor/commands/" + os.path.basename(cmd)] = HEADER + "\n\n" + b.replace("`$ARGUMENTS`", "the text typed after the command")
    return out


def copilot():
    out = {}
    for p in roles():
        m, b = split(p)
        desc = m.get("description", "").replace('"', "'")
        out[f".github/agents/{os.path.basename(p)[:-3]}.agent.md"] = f'---\ndescription: "{desc}"\n---\n{HEADER}\n\n{b}'
    sources = [os.path.join(ROOT, ".claude", "skills", "task", "SKILL.md")]
    sources += sorted(glob.glob(os.path.join(ROOT, ".claude", "commands", "*.md")))
    for p in sources:
        m, b = split(p)
        name = "task" if p.endswith("SKILL.md") else os.path.basename(p)[:-3]
        desc = m.get("description", "").replace('"', "'")
        body = b.replace("`$ARGUMENTS`", "the text typed after the prompt").replace("$ARGUMENTS", "the text typed after the prompt")
        out[f".github/prompts/{name}.prompt.md"] = f'---\ndescription: "{desc}"\n---\n{HEADER}\n\n{body}'
    return out


def codex():
    lines = [BEGIN, HEADER, "", "## Agent flow", "",
             "Implementation work follows `.claude/skills/task/SKILL.md` and the protocol in",
             "`.claude/kit/PROTOCOL.md`: the purpose and every stage's result live on disk in",
             "`.work/<ID>/`, never only in the conversation.", "",
             "Codex runs the stages one at a time. Start each stage in a **new session**, give it the",
             "work directory, and tell it to act as the role in its file:", ""]
    for p in roles():
        m, _ = split(p)
        name = os.path.basename(p)[:-3]
        lines.append(f"- `{name}`: `.claude/agents/{name}.md`. {m.get('description', '').split('. ')[0].rstrip('.')}.")
    lines += ["",
              "- Before each next stage run `bash .claude/kit/scripts/work.sh status`: it checks every",
              "  stage file and exits non-zero on a missing section or a `FAIL` verdict.",
              "- Setup: when the dev asks to set up the flow, or names the task tracker or where",
              "  product documentation lives, follow `.claude/commands/flow-setup.md`.",
              "- Specialized agents (create, move, remove, and their room): follow `.claude/commands/flow-agent.md`.",
             "- Product sources: `.claude/product-sources.md`. When the dev asks to add or sync a",
              "  product source, follow `.claude/commands/product-source.md`.",
              "- Each stage file starts with `Status:` (refiner, executor, tester) or `Verdict:` (reviewers),",
              "  and cites every acceptance criterion (`AC-001`...) of `00-purpose.md`. An open",
              "  `[NEEDS CLARIFICATION: ...]` in the contract means: ask the dev before implementing.",
              "- Learnings by lens: `python3 .claude/kit/scripts/learnings.py --lens <lens>`.",
              END, ""]
    block = "\n".join(lines)
    path = os.path.join(ROOT, "AGENTS.md")
    current = open(path).read() if os.path.exists(path) else ""
    if BEGIN in current and END in current:
        new = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", lambda _: block, current, flags=re.S)
    else:
        new = (current.rstrip() + "\n\n" if current.strip() else "") + block
    return {"AGENTS.md": new}


def installed_tools():
    found = set()
    if os.path.exists(os.path.join(ROOT, ".cursor", "rules", "task.mdc")):
        found.add("cursor")
    agents_md = os.path.join(ROOT, "AGENTS.md")
    if os.path.exists(agents_md) and BEGIN in open(agents_md).read():
        found.add("codex")
    if os.path.exists(os.path.join(ROOT, ".github", "prompts", "task.prompt.md")):
        found.add("copilot")
    return ",".join(sorted(found)) or "cursor,codex"


def main():
    ap = argparse.ArgumentParser(description="Project the .claude sources for Cursor and Codex.")
    ap.add_argument("--tools", help="comma-separated: cursor, codex, copilot (default: the ones already projected)")
    ap.add_argument("--check", action="store_true", help="exit 1 if a projection is stale, write nothing")
    opts = ap.parse_args()
    tools = set((opts.tools or installed_tools()).split(",")) - {"claude"}
    known = {"cursor", "codex", "copilot"}
    if tools - known:
        ap.error(f"unknown tools: {', '.join(sorted(tools - known))}")
    out = {}
    if "cursor" in tools:
        out.update(cursor())
    if "codex" in tools:
        out.update(codex())
    if "copilot" in tools:
        out.update(copilot())
    stale = []
    for rel, text in sorted(out.items()):
        path = os.path.join(ROOT, rel)
        if os.path.exists(path) and open(path).read() == text:
            continue
        stale.append(rel)
        if not opts.check:
            os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
            with open(path, "w") as f:
                f.write(text)
        print(("stale  " if opts.check else "wrote  ") + rel)
    return 1 if opts.check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
